// Run with the host Playwright code tool. All writes stay in a fresh browser context.
async (page) => {
  const context = await page.context().browser().newContext({ viewport: { width: 1440, height: 1000 } });
  const probe = await context.newPage();
  const origin = "http://127.0.0.1:8002";
  const results = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); results.push(message); };
  try {
    await probe.goto(origin);
    await probe.locator(".figure-painted").first().waitFor();
    check((await probe.locator("h1").textContent()).includes("toman forma"), "Campaign homepage renders");
    check(await probe.locator(".fr-brand img").getAttribute("src") === "/ferready/logo-light.svg", "Official logo file is used");
    check(await probe.locator(".campaign-purchase .button").evaluate((el) => getComputedStyle(el).color === "rgb(29, 54, 89)"), "Desktop purchase label contrasts with its light button");
    await probe.getByRole("button", { name: /Para organizar/ }).click();
    check((await probe.locator(".campaign-buy h2").textContent()).includes("Caja"), "Campaign selection changes product and purchase information together");
    await probe.getByRole("searchbox", { name: "Buscar productos" }).fill("manguera");
    await probe.getByRole("button", { name: "Buscar", exact: true }).click();
    await probe.waitForURL("**/catalogo?q=manguera");
    await probe.locator(".product-card h3 a").first().click();
    await probe.waitForURL("**/p/manguera-flexible-50cm");
    check((await probe.locator("h1").textContent()).includes("Manguera"), "Direct search still opens the correct product");
    await probe.getByRole("button", { name: "Aumentar cantidad", exact: true }).click();
    await probe.getByRole("button", { name: "Añadir al carrito", exact: true }).click();
    await probe.waitForFunction(() => JSON.parse(localStorage.getItem("ferready-demo-cart-v1") || "[]")[0]?.quantity === 2);
    check(true, "Existing quantity and cart behavior is preserved");
    await probe.locator(".product-journey").scrollIntoViewIfNeeded();
    await probe.waitForFunction(() => document.querySelector(".product-journey")?.classList.contains("is-enhanced"));
    await probe.getByRole("link", { name: "A tu caja", exact: true }).click();
    await probe.waitForFunction(() => document.querySelector(".product-journey")?.getAttribute("data-packed") === "true");
    check(await probe.getByRole("button", { name: "Comprar este producto", exact: true }).isVisible(), "Product packs into its box beside the final purchase action");
    await probe.getByRole("link", { name: "Tu proyecto", exact: true }).click();
    await probe.waitForFunction(() => document.querySelector(".product-journey")?.getAttribute("data-phase") === "1");
    check(await probe.locator(".journey-copy article").nth(1).isVisible(), "Reverse scrolling restores the correct product chapter");
    await probe.getByRole("button", { name: "Ver sin animación", exact: true }).click();
    check(!(await probe.locator(".product-journey").getAttribute("class")).includes("is-enhanced"), "Animation can be disabled without losing the content");
    check(await probe.locator(".journey-object").evaluate((el) => !el.style.transform), "Static mode restores the untransformed product image");
    await probe.emulateMedia({ reducedMotion: "reduce" });
    await probe.reload();
    check(await probe.getByRole("button", { name: "Comprar este producto", exact: true }).count() === 1, "Reduced-motion purchase remains available");
    check(!await probe.locator(".product-journey").evaluate((el) => el.classList.contains("is-enhanced")), "Reduced motion has no pinned scroll journey");
    await probe.setViewportSize({ width: 390, height: 844 });
    await probe.emulateMedia({ reducedMotion: "no-preference" });
    await probe.goto(origin);
    check(!await probe.evaluate(() => document.documentElement.scrollWidth > innerWidth), "Mobile homepage has no horizontal overflow");
    await probe.getByRole("button", { name: "Abrir menú", exact: true }).focus();
    await probe.keyboard.press("Enter");
    check(await probe.getByRole("link", { name: "Todos los productos", exact: true }).first().isVisible(), "Mobile navigation remains usable");
    await probe.goto(`${origin}/p/taladro-bauker-12v`);
    await probe.getByRole("button", { name: "Ver imagen 2", exact: true }).click();
    check((await probe.locator(".gallery-main img").getAttribute("src")).includes("484299_01"), "Existing product gallery still changes its image");
    check(!await probe.evaluate(() => document.documentElement.scrollWidth > innerWidth), "Mobile product page has no horizontal overflow");
    await probe.getByRole("link", { name: "A tu caja", exact: true }).click();
    await probe.waitForFunction(() => document.querySelector(".product-journey")?.getAttribute("data-packed") === "true");
    check(await probe.getByRole("button", { name: "Comprar este producto", exact: true }).isVisible(), "Animated mobile journey reaches its purchase action");
    const buyBox = await probe.getByRole("button", { name: "Comprar este producto", exact: true }).boundingBox();
    const parcelBox = await probe.locator(".shipping-parcel").boundingBox();
    check(buyBox.y >= 124 && buyBox.y + buyBox.height <= 844, "Mobile purchase is fully inside the viewport below the header");
    check(parcelBox.y >= 124 && parcelBox.y + parcelBox.height <= 844, "Mobile shipping box is fully inside the viewport");
    await probe.getByRole("button", { name: "Comprar este producto", exact: true }).click();
    await probe.waitForURL("**/checkout");
    check(await probe.locator("h1").count() === 1, "Final journey purchase reaches the simulated checkout");
    await probe.emulateMedia({ reducedMotion: "reduce" });
    await probe.addInitScript(() => { HTMLCanvasElement.prototype.getContext = () => null; });
    await probe.goto(`${origin}/p/taladro-bauker-12v`);
    check(await probe.locator(".journey-object .product-figure img").isVisible(), "Canvas unavailability preserves the original photograph");
    await probe.route("**/ferready/products/**", (route) => route.abort());
    await probe.reload();
    await probe.locator(".journey-object .figure-fallback").waitFor();
    check(await probe.getByRole("button", { name: "Comprar este producto", exact: true }).count() === 1, "Failed product imagery does not remove the buying controls");
    await probe.unroute("**/ferready/products/**");
    await probe.setViewportSize({ width: 390, height: 650 });
    await probe.emulateMedia({ reducedMotion: "no-preference" });
    await probe.reload();
    check(!await probe.locator(".product-journey").evaluate((el) => el.classList.contains("is-enhanced")), "Short viewports receive the full unpinned product content");
    return results;
  } finally {
    await context.close();
  }
}
